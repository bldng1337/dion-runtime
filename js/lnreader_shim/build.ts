// Bundles the shim into the asset the lnreader crate embeds. The output is
// committed so cargo builds (including Flutter's cargokit) need no JS tooling;
// rerun this (or `bunx turbo build`) after changing the shim.

const OUTPUT = `${import.meta.dir}/../../rust/lnreader/assets/generated_lnreader_shim.js`;

// Host modules provided by the Dion runtime.
const external = ["network", "setting", "parse", "cache", "convert"];

const result = await Bun.build({
	entrypoints: [`${import.meta.dir}/src/index.ts`],
	format: "esm",
	target: "browser",
	minify: true,
	external,
});
if (!result.success) {
	for (const log of result.logs) console.error(log);
	process.exit(1);
}
const [output] = result.outputs;
if (!output) throw new Error("bun build produced no output");
const banner =
	"// GENERATED by js/lnreader_shim (bun run build). Do not edit by hand.\n";
await Bun.write(OUTPUT, banner + (await output.text()));
console.log(`Wrote ${OUTPUT} (${output.size} bytes)`);
